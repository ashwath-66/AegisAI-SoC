#!/usr/bin/env python3
# Flatten one IP into a single self-contained SystemVerilog file (all `include directives expanded inline).
#   python3 flow/flatten_ip.py aegis_cpu          -> ip/aegis_cpu/release/aegis_cpu_flat.sv
# Run from the project root. The flat file is for PACKAGING / delivery; the multi-file rtl/ stays the source of truth.
import os, re, sys
ip = sys.argv[1]
lines = [l.strip() for l in open(f'ip/{ip}/rtl.f') if l.strip() and not l.startswith('//')]
incs = [l[len('+incdir+'):] for l in lines if l.startswith('+incdir+')]
srcs = [l for l in lines if not l.startswith('+')]
missing = []
INC = re.compile(r'^\s*`include\s+"([^"]+)"')
def find(name, cur):
    for d in [os.path.dirname(cur)] + incs:
        p = os.path.join(d, name)
        if os.path.exists(p): return p
    return None                      # not found: only legal inside an `ifdef that is never taken (e.g. formal_tb_frag.svh)
def expand(path, depth=0):
    if depth > 12: raise RuntimeError("include nesting too deep: " + path)
    out = []
    for ln in open(path).read().split('\n'):
        m = INC.match(ln)
        if m:
            p = find(m.group(1), path)
            if p is None:
                missing.append(m.group(1)); out.append(ln + "  // (not found - left as is)"); continue
            out.append(f"// ---- begin include {os.path.basename(p)} ----")
            out.extend(expand(p, depth + 1))
            out.append(f"// ---- end include {os.path.basename(p)} ----")
        else:
            out.append(ln)
    return out
os.makedirs(f'ip/{ip}/release', exist_ok=True)
dst = f'ip/{ip}/release/{ip}_flat.sv'
with open(dst, 'w') as f:
    f.write(f"// {ip}: flattened release file generated by flow/flatten_ip.py - do not edit, edit rtl/ and regenerate\n")
    for s in srcs:
        f.write(f"\n// ======== {os.path.basename(s)} ========\n")
        f.write('\n'.join(expand(s)) + '\n')
t = open(dst).read()
nmod = len(re.findall(r'^\s*module\s', t, re.M)); ninc = len(re.findall(r'^\s*`include', t, re.M))
print(f"{dst}: {len(srcs)} files -> 1 file, {t.count(chr(10))} lines, {nmod} modules, remaining include directives: {ninc}")
if missing: print("  includes not found (left as is, expected only inside never-taken `ifdef):", sorted(set(missing)))
