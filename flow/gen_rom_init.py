#!/usr/bin/env python3
# Bake the firmware into the ROM IP so it never needs an external boot.hex file.
#   python3 flow/gen_rom_init.py            (run from the project root, after every firmware change)
# 1. soc/fw/boot.hex  ->  ip/aegis_rom/rtl/rom_init.svh   (mem[i] = 32'h........;)
# 2. axil_rom.sv uses `include "rom_init.svh" for synthesis (simulation still takes +FW=<file>)
# 3. ip/aegis_rom/rtl.f gets the include directory
import re
words = [l.strip() for l in open('soc/fw/boot.hex') if l.strip() and not l.startswith('//') and not l.startswith('@')]
with open('ip/aegis_rom/rtl/rom_init.svh', 'w') as f:
    f.write("// generated by flow/gen_rom_init.py from soc/fw/boot.hex - do not edit\n")
    for i, w in enumerate(words):
        f.write(f"mem[{i}] = 32'h{w};\n")
print(f"rom_init.svh: {len(words)} firmware words")

p = 'ip/aegis_rom/rtl/axil_rom.sv'
s = open(p).read()
if '`include "rom_init.svh"' in s:
    print("axil_rom.sv: already patched")
else:
    old = '''        // Vivado: no 'string' variables / plusargs; plain literal file name.
        for (int i = 0; i < WORDS; i++) mem[i] = 32'h0000_0013;       // NOP padding
        $readmemh("boot.hex", mem);'''
    new = '''        // Synthesis: firmware is part of the IP (generated by flow/gen_rom_init.py), no external file.
        for (int i = 0; i < WORDS; i++) mem[i] = 32'h0000_0013;       // NOP padding
        `include "rom_init.svh"'''
    assert old in s, "axil_rom.sv pattern not found"
    open(p, 'w').write(s.replace(old, new)); print("axil_rom.sv: patched")

p = 'ip/aegis_rom/rtl.f'
s = open(p).read()
if '+incdir+ip/aegis_rom/rtl' not in s:
    open(p, 'w').write('+incdir+ip/aegis_rom/rtl\n' + s); print("rtl.f: include dir added")
