`timescale 1ns / 1ps
//-----------------------------------------------------------------------------
// axil_rom : boot ROM, 32-bit words, read only (writes answer SLVERR)
//   Content: $readmemh file (one 32-bit hex word per line).
//   Path: +FW=<file> plusarg if given, else the INIT_FILE parameter.
//-----------------------------------------------------------------------------
module axil_rom #(
    parameter int    WORDS     = 4096,
    parameter string INIT_FILE = "boot.hex"
) (
    input  logic        clk,
    input  logic        rst_n,
    input  logic [31:0] s_awaddr,  input logic s_awvalid, output logic s_awready,
    input  logic [31:0] s_wdata,   input logic [3:0] s_wstrb,
    input  logic        s_wvalid,  output logic s_wready,
    output logic [1:0]  s_bresp,   output logic s_bvalid, input logic s_bready,
    input  logic [31:0] s_araddr,  input logic s_arvalid, output logic s_arready,
    output logic [31:0] s_rdata,   output logic [1:0] s_rresp,
    output logic        s_rvalid,  input logic s_rready
);
    localparam int AWB = $clog2(WORDS);
    logic [31:0] mem [WORDS];

    initial begin
`ifdef SYNTHESIS
        // Synthesis: firmware is part of the IP (generated by flow/gen_rom_init.py), no external file.
        for (int i = 0; i < WORDS; i++) mem[i] = 32'h0000_0013;       // NOP padding
        `include "rom_init.svh"
`else
        string f;
        for (int i = 0; i < WORDS; i++) mem[i] = 32'h0000_0013;       // NOP padding
        f = INIT_FILE;
        void'($value$plusargs("FW=%s", f));
        $readmemh(f, mem);
`endif
    end

    logic        rd_en;
    logic [AWB+1:0] rd_addr;
    logic [31:0] rd_q;

    axil_regif #(.AW(AWB+2)) u_if (
        .clk(clk), .rst_n(rst_n),
        .s_awaddr(s_awaddr), .s_awvalid(s_awvalid), .s_awready(s_awready),
        .s_wdata(s_wdata), .s_wstrb(s_wstrb), .s_wvalid(s_wvalid), .s_wready(s_wready),
        .s_bresp(s_bresp), .s_bvalid(s_bvalid), .s_bready(s_bready),
        .s_araddr(s_araddr), .s_arvalid(s_arvalid), .s_arready(s_arready),
        .s_rdata(s_rdata), .s_rresp(s_rresp), .s_rvalid(s_rvalid), .s_rready(s_rready),
        .wr_en(), .wr_addr(), .wr_data(), .wr_strb(), .wr_err(1'b1),
        .rd_en(rd_en), .rd_addr(rd_addr), .rd_data(rd_q), .rd_err(1'b0)
    );
    always_ff @(posedge clk) rd_q <= mem[rd_addr[AWB+1:2]];
endmodule
